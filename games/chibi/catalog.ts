// The chibi catalogue as the NFT contract (contracts/chibi) sees it, built from LOOK_CHOICES (games/ma-soi/look.ts):
// which parts are a character's own (body, skin, hair colour, outfit colour: free to change, never tokens) and which are
// items (one NFT per piece). Index 0 of every item part is the bare default and needs no token. Pure, so the server,
// the browser, the tests and the generator of contracts/chibi/src/catalog.rs all share it.

import { ITEM_PARTS, LOOK_CHOICES, rarityOf, type ItemPart, type Look, type LookPart, type Rarity } from "../ma-soi/look.ts";
import { NAMES_EN, RARITY_EN } from "./names.ts";

export { ITEM_PARTS, type ItemPart };
/** A character's own traits: chosen freely, stored on the character, never minted. */
export const TRAIT_PARTS = ["body", "skin", "hairColor", "robe"] as const satisfies readonly LookPart[];
export type TraitPart = (typeof TRAIT_PARTS)[number];

export type CatalogItem = { kind: string; part: ItemPart; index: number; name: string; rarity: Rarity };

/** `outfit:5`, the kind of an item; a token's id is `<kind>:<serial>`. */
export const kindOf = (part: ItemPart, index: number): string => `${part}:${index}`;

/** Every item that can be a token (index 0 of each part is the bare default and is not one). */
export const CATALOG: readonly CatalogItem[] = ITEM_PARTS.flatMap((part) =>
  LOOK_CHOICES[part].flatMap((_, index): CatalogItem[] =>
    index === 0 ? [] : [{ kind: kindOf(part, index), part, index, name: NAMES_EN[part][index], rarity: rarityOf(part, index) }],
  ),
);
const BY_KIND = new Map(CATALOG.map((item) => [item.kind, item]));

export const itemOfKind = (kind: string): CatalogItem | undefined => BY_KIND.get(kind);

/** The item a token id names (`hat:6:41` is a Mandarin cap), or `undefined` for a character's token or anything else. */
export function itemOfToken(tokenId: string): CatalogItem | undefined {
  const match = /^([a-zA-Z]+):(\d+):\d+$/.exec(tokenId);
  return match ? BY_KIND.get(`${match[1]}:${match[2]}`) : undefined;
}

export const isCharacterToken = (tokenId: string): boolean => tokenId.startsWith("char:");

export const nameOf = (part: LookPart, index: number): string => NAMES_EN[part][index] ?? `#${index}`;
export const rarityName = (rarity: Rarity): string => RARITY_EN[rarity];

/** Basic items: free, minted one of each per account. Rare and better come only out of boxes. */
export const BASIC_ITEMS: readonly CatalogItem[] = CATALOG.filter((item) => item.rarity === 0);
export const BOX_ITEMS: readonly CatalogItem[] = CATALOG.filter((item) => item.rarity > 0);

/** The look a character starts from when nothing is chosen yet. */
export const BARE_LOOK: Look = { body: 0, skin: 1, hair: 2, hairColor: 0, outfit: 0, robe: 3, neck: 0, hat: 0, face: 0, held: 0, shoes: 0, pet: 0, ride: 0 };

/** Whether a look uses only basic items (what a new character may be made of). */
export const isBasicLook = (look: Look): boolean => ITEM_PARTS.every((part) => rarityOf(part, look[part]) === 0);

/** Item kinds a look wears (index 0 is not an item). */
export const wornKinds = (look: Look): string[] => ITEM_PARTS.flatMap((part) => (look[part] > 0 ? [kindOf(part, look[part])] : []));

/** contracts/chibi/src/catalog.rs, generated from the tables above (`npm run chibi:catalog`; a test checks it is current). */
export function catalogRust(): string {
  const quote = (text: string) => JSON.stringify(text);
  const lines = [
    "// Generated by scripts/chibi-catalog.ts from games/ma-soi/look.ts and games/chibi/names.ts. Do not edit by hand:",
    "// change those files and run `npm run chibi:catalog`.",
    "",
    "/// A character's own traits and how many choices each has. Free to change, never tokens.",
    `pub const TRAITS: [(&str, u8); ${TRAIT_PARTS.length}] = [${TRAIT_PARTS.map((part) => `(${quote(part)}, ${LOOK_CHOICES[part].length})`).join(", ")}];`,
    "",
    "/// Item parts, in the order of `ITEMS`.",
    `pub const ITEM_PARTS: [&str; ${ITEM_PARTS.length}] = [${ITEM_PARTS.map(quote).join(", ")}];`,
    "",
    "/// Per item part, per index: (rarity, English name). Rarity 0 Basic, 1 Rare, 2 Epic, 3 Legendary. Index 0 is the bare",
    "/// default of the part and is never a token.",
    `pub const ITEMS: [&[(u8, &str)]; ${ITEM_PARTS.length}] = [`,
    ...ITEM_PARTS.map((part) => `    &[${LOOK_CHOICES[part].map((_, index) => `(${rarityOf(part, index)}, ${quote(NAMES_EN[part][index])})`).join(", ")}],`),
    "];",
    "",
  ];
  return lines.join("\n");
}
