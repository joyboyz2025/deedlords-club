//! Turns `shared/board.json` into Rust statics (`$OUT_DIR/board_data.rs`) so the contract never parses JSON at runtime.
//!
//! The board file is found at `../../shared/board.json` relative to this crate. Set `DEEDLORDS_BOARD_JSON` to another
//! path when building somewhere that only sees `contracts/` (for example a reproducible-build container).

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use serde_json::Value;

fn main() {
    println!("cargo:rerun-if-env-changed=DEEDLORDS_BOARD_JSON");
    let path = match env::var("DEEDLORDS_BOARD_JSON") {
        Ok(path) => PathBuf::from(path),
        Err(_) => PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../shared/board.json"),
    };
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let board: Value = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{} is not valid JSON: {e}", path.display()));
    let code = generate(&board);
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("board_data.rs");
    fs::write(&out, code).unwrap();
}

fn int(value: &Value, what: &str) -> i64 {
    value.as_i64().unwrap_or_else(|| panic!("board.json: {what} must be an integer, got {value}"))
}

fn field<'a>(value: &'a Value, key: &str, what: &str) -> &'a Value {
    value.get(key).unwrap_or_else(|| panic!("board.json: {what} has no `{key}`"))
}

fn ints(value: &Value, what: &str) -> Vec<i64> {
    value.as_array().unwrap_or_else(|| panic!("board.json: {what} must be an array")).iter().map(|v| int(v, what)).collect()
}

fn deck(value: &Value, what: &str) -> &'static str {
    match value.as_str() {
        Some("chance") => "Deck::Chance",
        Some("chest") => "Deck::Chest",
        _ => panic!("board.json: {what} has unknown deck {value}"),
    }
}

fn generate(board: &Value) -> String {
    let constants = field(board, "constants", "root");
    let c = |key: &str| int(field(constants, key, "constants"), key);
    let board_size = c("boardSize");
    let jail = c("jail");
    let station_rents = ints(field(constants, "stationRents", "constants"), "stationRents");
    let utility_times = ints(field(constants, "utilityTimes", "constants"), "utilityTimes");
    let groups = field(board, "groups", "root").as_array().expect("groups must be an array").len();

    let squares = field(board, "squares", "root").as_array().expect("squares must be an array");
    assert_eq!(squares.len() as i64, board_size, "board.json: squares.len() must equal constants.boardSize");
    assert!(board_size > 0 && board_size <= 255, "board.json: boardSize must fit in a u8");

    let mut out = String::new();
    writeln!(out, "// @generated by build.rs from shared/board.json. Do not edit.").unwrap();
    for (name, key) in [("START_CASH", "startCash"), ("SALARY", "salary"), ("JAIL_FINE", "jailFine")] {
        writeln!(out, "/// `constants.{key}` from board.json.\npub const {name}: i64 = {};", c(key)).unwrap();
    }
    writeln!(out, "/// Index of the jail square.\npub const JAIL: u8 = {jail};").unwrap();
    writeln!(out, "/// Number of squares.\npub const BOARD_SIZE: u8 = {board_size};").unwrap();
    writeln!(out, "/// Station rent by number of stations owned (index = count - 1).").unwrap();
    writeln!(out, "pub const STATION_RENTS: [i64; {}] = {:?};", station_rents.len(), station_rents).unwrap();
    writeln!(out, "/// Utility rent multiplier by number of utilities owned (index = count - 1).").unwrap();
    writeln!(out, "pub const UTILITY_TIMES: [i64; {}] = {:?};", utility_times.len(), utility_times).unwrap();

    let mut ownable = Vec::new();
    let mut group_members = vec![Vec::new(); groups];
    let (mut stations, mut utilities) = (0, 0);
    writeln!(out, "/// The squares, clockwise from Departure.\npub static SQUARES: [Square; {}] = [", squares.len()).unwrap();
    for (i, square) in squares.iter().enumerate() {
        let what = format!("squares[{i}]");
        let kind = field(square, "kind", &what).as_str().unwrap_or_else(|| panic!("{what}.kind must be a string"));
        let price = || {
            let price = int(field(square, "price", &what), &what);
            assert!(price > 0, "{what}: price must be positive");
            price
        };
        let rust = match kind {
            "start" => "Square::Start".to_string(),
            "jail" => "Square::Jail".to_string(),
            "rest" => "Square::Rest".to_string(),
            "arrest" => "Square::Arrest".to_string(),
            "city" => {
                let group = int(field(square, "group", &what), &what);
                assert!(group >= 0 && (group as usize) < groups, "{what}: group out of range");
                group_members[group as usize].push(i);
                ownable.push(i);
                format!("Square::City {{ group: {group}, price: {} }}", price())
            }
            "station" => {
                stations += 1;
                ownable.push(i);
                format!("Square::Station {{ price: {} }}", price())
            }
            "utility" => {
                utilities += 1;
                ownable.push(i);
                format!("Square::Utility {{ price: {} }}", price())
            }
            "tax" => format!("Square::Tax {{ amount: {} }}", int(field(square, "amount", &what), &what)),
            "card" => format!("Square::Card {{ deck: {} }}", deck(field(square, "deck", &what), &what)),
            other => panic!("{what}: unknown kind {other}"),
        };
        let name = square.get("name").and_then(Value::as_str).unwrap_or("");
        writeln!(out, "    {rust}, // {i}: {name}").unwrap();
    }
    writeln!(out, "];").unwrap();
    assert_eq!(
        field(&squares[jail as usize], "kind", "jail square").as_str(),
        Some("jail"),
        "constants.jail must point at the jail square"
    );
    assert_eq!(stations, station_rents.len(), "one station rent per station");
    assert_eq!(utilities, utility_times.len(), "one utility multiplier per utility");

    writeln!(out, "/// Ownable square indexes (cities, stations, utilities), ascending.").unwrap();
    writeln!(out, "pub static OWNABLE: [u8; {}] = {:?};", ownable.len(), ownable).unwrap();
    writeln!(out, "/// City indexes of each colour group, in board order.").unwrap();
    writeln!(out, "pub static GROUPS: [&[u8]; {groups}] = [").unwrap();
    for members in &group_members {
        assert!(!members.is_empty(), "every group needs at least one city");
        writeln!(out, "    &{members:?},").unwrap();
    }
    writeln!(out, "];").unwrap();

    let cards = field(board, "cards", "root");
    for (deck_key, name) in [("chance", "CHANCE"), ("chest", "CHEST")] {
        let list = field(cards, deck_key, "cards").as_array().expect("card deck must be an array");
        assert!(!list.is_empty(), "deck {deck_key} is empty");
        writeln!(out, "/// The `{deck_key}` deck, in board.json order (the card index is the position here).").unwrap();
        writeln!(out, "pub static {name}: [CardEffect; {}] = [", list.len()).unwrap();
        for (i, card) in list.iter().enumerate() {
            let what = format!("cards.{deck_key}[{i}]");
            let effect = field(card, "effect", &what);
            let kind = field(effect, "kind", &what).as_str().unwrap_or_else(|| panic!("{what}.effect.kind must be a string"));
            let num = |key: &str| int(field(effect, key, &what), &what);
            let rust = match kind {
                "money" => format!("CardEffect::Money {{ amount: {} }}", num("amount")),
                "goto" => {
                    let to = num("to");
                    assert!(to >= 0 && to < board_size, "{what}: goto target out of range");
                    format!("CardEffect::Goto {{ to: {to} }}")
                }
                "back" => {
                    let steps = num("steps");
                    assert!(steps > 0 && steps < board_size, "{what}: back steps out of range");
                    format!("CardEffect::Back {{ steps: {steps} }}")
                }
                "nearest" => match field(effect, "type", &what).as_str() {
                    Some("station") => "CardEffect::Nearest { kind: Nearest::Station }".to_string(),
                    Some("utility") => "CardEffect::Nearest { kind: Nearest::Utility }".to_string(),
                    other => panic!("{what}: unknown nearest type {other:?}"),
                },
                "jail" => "CardEffect::Jail".to_string(),
                "free" => "CardEffect::Free".to_string(),
                "each" => format!("CardEffect::Each {{ amount: {} }}", num("amount")),
                "repairs" => format!("CardEffect::Repairs {{ house: {}, hotel: {} }}", num("house"), num("hotel")),
                other => panic!("{what}: unknown effect {other}"),
            };
            writeln!(out, "    {rust}, // {i}").unwrap();
        }
        writeln!(out, "];").unwrap();
    }
    out
}
